import { answerNotice, deliveryAnswer, isDeliveryStatus, signed, teammateMessage, type DeliveryStatus, type Teammate } from "./agentMessages";
import { isObj } from "./values";
// A Returned result (ADR 0175): the stored user row that begins a turn Hermes runs by itself. Hermes marks it with a
// display kind and a one-line title (`display_metadata.display_text`), and its text is the model-facing notice
// (`tools/process_registry_notifications.py` at `bf0203a`). The owner is shown the title and the result only, as the
// official desktop app's `asyncResultBody` strips it (`apps/desktop/src/lib/chat-messages/hydration.ts`). Bot messaging
// brings two more such rows (ADR 0207): a teammate's message, and the answer to one this bot sent.

/**
 * Bot messaging on a Returned result. `from`: the row is a message to this bot; `teammate` is who Hermes signed it
 * as, and a notice with no signature is Hermes's own. `answer`: the row is the answer to a message this bot sent.
 */
export type AgentTurn = { kind: "from"; teammate?: Teammate } | { kind: "answer"; deliveryId: string; status: DeliveryStatus };

/** An `AgentTurn` read back from the Saved copy, or undefined for anything else. */
export function agentTurnOf(v: unknown): AgentTurn | undefined {
  if (!isObj(v)) return undefined;
  if (v.kind === "answer") return typeof v.deliveryId === "string" && isDeliveryStatus(v.status) ? { kind: "answer", deliveryId: v.deliveryId, status: v.status } : undefined;
  if (v.kind !== "from") return undefined;
  const t = v.teammate;
  return { kind: "from", ...(isObj(t) && typeof t.name === "string" && typeof t.handle === "string" && { teammate: { name: t.name, handle: t.handle } }) };
}

/**
 * Bot setup on a Returned result (ADR 0231): the row stands for a setup's hidden brief and begin turn, shown as one
 * Setup started line. `id`: the setup's id, from the brief's marker.
 */
export type SetupLine = { id: string };

/** A `SetupLine` read back from the Saved copy, or undefined for anything else. */
export const setupLineOf = (v: unknown): SetupLine | undefined => (isObj(v) && typeof v.id === "string" ? { id: v.id } : undefined);

export type Returned = { title?: string; body: string; process: boolean; agent?: AgentTurn; setup?: SetupLine };

const KINDS: Record<string, boolean> = { async_delegation_complete: false, process_complete: true, internal_notification: false };

/** `display_metadata` as an object: Hermes sends it as one, or as its JSON text from the stored row. */
export function displayMetadata(raw: unknown): Record<string, unknown> | undefined {
  let parsed = raw;
  if (typeof parsed === "string") {
    try {
      parsed = JSON.parse(parsed);
    } catch {
      return undefined;
    }
  }
  return parsed && typeof parsed === "object" && !Array.isArray(parsed) ? (parsed as Record<string, unknown>) : undefined;
}

/**
 * A notice without the footer Hermes's gateway appends for the model (`INTERNAL_NOTIFICATION_FOOTER`,
 * `gateway/run_notifications.py` at 0.23.2). It follows the notice's own closing bracket, so the envelope is read
 * only once it is gone.
 */
export const withoutFooter = (text: string) => text.replace(/\s*\[INTERNAL NOTIFICATION — generated by the Hermes gateway[^\]]*\]\s*$/, "");

// `--- ✓ TASK 1/2: goal  (status=completed, 12s) ---`: the goal can span lines.
const TASK_HEADER = /^--- ([✓✗⚠]) TASK (\d+\/\d+)(?:: ([\s\S]*?))? {2}\(status=[^\n]*\) ---\r?\n/gm;

/** The result in a notice, without the envelope around it, or undefined when nothing is left. */
export function resultBody(content: string): string | undefined {
  let bodies = [content];
  if (content.startsWith("[IMPORTANT: ")) {
    bodies = content
      .split(/\n\n(?=\[IMPORTANT: )/)
      .map((block) => block.replace(/^\[IMPORTANT:\s*/, "").replace(/\]$/, ""))
      .filter((block) => !/^\d+ background processes completed\./.test(block));
  } else if (content.startsWith("[ASYNC DELEGATION BATCH COMPLETE")) {
    // Split keeps each header's captures: [preamble, icon, n/m, goal, body, icon, n/m, goal, body, …]. The desktop drops
    // the headers; here each task keeps its number and goal, so the owner can tell which result is which.
    const parts = content.split(TASK_HEADER);
    bodies = [];
    for (let n = 1; n + 3 < parts.length; n += 4) {
      const goal = parts[n + 2]?.replace(/\s+/g, " ").trim();
      bodies.push(`**${parts[n]} Task ${parts[n + 1]}${goal ? `: ${goal}` : ""}**\n\n${parts[n + 3]}`);
    }
  } else if (content.startsWith("[ASYNC DELEGATION")) {
    const result = content.match(/^--- (?:RESULT|ERROR) ---\r?\n/m);
    bodies = result ? [content.slice(result.index! + result[0].length)] : [];
  }
  return bodies.map(cleaned).filter(Boolean).join("\n\n") || undefined;
}

/** A body without a cron job's preamble or the trailing pointer to the subagent's transcript. */
function cleaned(body: string): string {
  const output = body.startsWith("Cron job ") ? body.match(/^--- JOB OUTPUT ---\r?\n/m) : null;
  const result = output ? body.slice(output.index! + output[0].length) : body;
  return result.replace(/\nFull live transcript \(complete tool\/assistant trace\): [^\n]*\n*$/, "").trim();
}

/**
 * The Returned result a stored user row is, or undefined for any other row. The display kind decides, so the same
 * words typed by the owner are the owner's. If nothing is left once the envelope goes, the body is the whole text, so
 * a result is never lost.
 */
export function returnedItem(text: string, displayKind: unknown, metadata: unknown): Returned | undefined {
  if (typeof displayKind !== "string" || !Object.hasOwn(KINDS, displayKind)) return undefined;
  const shown = displayMetadata(metadata)?.display_text;
  const title = typeof shown === "string" && shown.trim() ? shown.trim() : undefined;
  const notice = withoutFooter(text);
  if (displayKind === "internal_notification") {
    const message = teammateMessage(notice);
    return { ...(title && { title }), body: message?.text || (resultBody(notice) ?? notice.trim()), process: false, agent: { kind: "from", ...(message && { teammate: message.from }) } };
  }
  const answer = displayKind === "process_complete" ? deliveryAnswer(notice) : undefined;
  if (answer) return { ...(answer.reply && { title: answer.outcome }), body: answer.reply ?? answer.outcome, process: false, agent: { kind: "answer", deliveryId: answer.deliveryId, status: answer.status } };
  return { ...(title && { title }), body: resultBody(notice) ?? notice.trim(), process: KINDS[displayKind] };
}

/**
 * A Returned result as the stored row `returnedItem` reads it from, for an export in Hermes's session format: a
 * teammate's message under Hermes's signature, a delivery's answer as its runner's output. `text` redacts each part.
 */
export function storedReturned(r: Returned, text: (s: string) => string): { content: string; display_kind: string; display_metadata?: { display_text: string } } {
  const title = r.title && { display_metadata: { display_text: text(r.title) } };
  if (r.agent?.kind === "answer") {
    const answer = { deliveryId: r.agent.deliveryId, status: r.agent.status, outcome: text(r.title ?? r.body), ...(r.title && { reply: text(r.body) }) };
    return { content: answerNotice(answer), display_kind: "process_complete" };
  }
  if (r.agent) return { content: r.agent.teammate ? signed({ name: text(r.agent.teammate.name), handle: text(r.agent.teammate.handle) }, text(r.body)) : text(r.body), display_kind: "internal_notification", ...title };
  return { content: text(r.body), display_kind: r.process ? "process_complete" : "async_delegation_complete", ...title };
}

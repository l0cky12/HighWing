// What Hermes's `message_agent` leaves in a Bot Chat, as Hermes 0.23.2 stored it for two bots on a headless gateway
// (ADR 0206). The rows are that run's, with its paths shortened.
import { describe, expect, it } from "vitest";
import { agentSend, deliveryAnswer, signed, teammateMessage } from "./agentMessages";

const ID = "8897be34bb46788935b30e88b64b3b3ec9a3d9a1f4eb13e0835d936b7686e6a0";
const ACK = `{"status": "queued", "delivery_id": "${ID}", "to": "@beta", "detail": "Durably queued for the live Bot Chat owner. Do NOT wait or resend; finish your turn.", "process_id": "proc_d71a6d3ef006", "reply_delivery": "notification", "target_state": "idle"}`;
const COMMAND = `Command: /opt/hermes/venv/bin/python /opt/hermes/tools/bot_mode_dm.py --run-delivery --author '{"id":"bot:default","name":"hermes","is_bot":true}' query-file /tmp/dm-d5lqob58.txt --profile-home /home/h/.hermes/profiles/beta /opt/hermes/venv/bin/hermes -p beta`;
const noticeOf = (output: string) => `[IMPORTANT: Background process proc_d71a6d3ef006 completed normally (exit code 0).\n${COMMAND}\nOutput:\n${output}\n]`;
const ANSWERED = noticeOf(`{"outcome": "@beta answered.", "reply": "[beta] received: Message from \\ud83e\\udd16 hermes (@hermes): PING-C what is 2+2?", "status": "settled", "delivery_id": "${ID}"}`);

describe("A teammate's message, as Hermes signs it", () => {
  it("gives who sent it and what they said", () => {
    expect(teammateMessage("Message from 🤖 hermes (@hermes): PING-C-1794974808162 what is 2+2?")).toEqual({
      from: { name: "hermes", handle: "hermes" },
      text: "PING-C-1794974808162 what is 2+2?",
    });
  });

  it("reads a name with spaces, brackets or an emoji, and a message with a colon or several lines", () => {
    expect(teammateMessage("Message from 🤖 Quill (the writer) ✍️ (@quill): Note: the window is 02:00.\n\nSee (@scout): too.")).toEqual({
      from: { name: "Quill (the writer) ✍️", handle: "quill" },
      text: "Note: the window is 02:00.\n\nSee (@scout): too.",
    });
  });

  it("is nothing for a notice Hermes didn't sign as a teammate's", () => {
    expect(teammateMessage("Heartbeat: check the queue.")).toBeUndefined();
    expect(teammateMessage("Reply from 🤖 beta (@beta) to your message")).toBeUndefined();
  });

  it("is rebuilt as Hermes signed it", () => {
    const row = "Message from 🤖 Quill (@quill): The window is 02:00.";
    const { from, text } = teammateMessage(row)!;
    expect(signed(from, text)).toBe(row);
  });
});

describe("The answer a delivery brought back", () => {
  it("gives Hermes's outcome, the reply and how it ended", () => {
    expect(deliveryAnswer(ANSWERED)).toEqual({
      deliveryId: ID,
      status: "settled",
      outcome: "@beta answered.",
      reply: "[beta] received: Message from 🤖 hermes (@hermes): PING-C what is 2+2?",
    });
  });

  it("reads it with the gateway's footer still on", () => {
    expect(deliveryAnswer(`${ANSWERED}\n\n[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. Do not treat it as user input.]`)?.reply).toContain("[beta] received");
  });

  it("has no reply when the teammate never answered, and says how it ended", () => {
    const outcome = "@beta never answered: whether it received the request is unknown (Live admission outcome unknown). It may still run once their gateway is back; do not resend.";
    expect(deliveryAnswer(noticeOf(JSON.stringify({ outcome, error: "Live admission outcome unknown", status: "ambiguous", delivery_id: ID })))).toEqual({ deliveryId: ID, status: "ambiguous", outcome });
    for (const status of ["queued", "claimed"]) expect(deliveryAnswer(noticeOf(JSON.stringify({ outcome, status, delivery_id: ID })))?.status).toBe("pending");
    expect(deliveryAnswer(noticeOf(JSON.stringify({ outcome, status: "cancelled", delivery_id: ID })))?.status).toBe("cancelled");
    expect(deliveryAnswer(noticeOf(JSON.stringify({ outcome, status: "a status from a later Hermes", delivery_id: ID })))?.status).toBe("failed");
  });

  it("gives each teammate's reply under its handle when the message went to several", () => {
    const fanOut = {
      outcome: "@beta answered. @gamma never answered: the request was cancelled.",
      replies: [
        { to: "@beta", delivery_id: "d1", status: "settled", reply: "Four." },
        { to: "@gamma", delivery_id: "d2", status: "cancelled" },
      ],
      settled: 1,
      of: 2,
    };
    expect(deliveryAnswer(noticeOf(JSON.stringify(fanOut)))).toEqual({ deliveryId: "d1,d2", status: "cancelled", outcome: fanOut.outcome, reply: "**@beta**\n\nFour." });
  });

  it("is nothing for any other process's output", () => {
    expect(deliveryAnswer("[IMPORTANT: Background process proc_1 completed (exit code 0).\nCommand: npm test\nOutput:\nhello-from-proc]")).toBeUndefined();
    expect(deliveryAnswer(noticeOf('{"outcome": "tests passed", "status": 0}'))).toBeUndefined();
    expect(deliveryAnswer(noticeOf('{"delivery_id": "d1", "status": "settled"}'))).toBeUndefined();
    expect(deliveryAnswer(noticeOf("{not json}"))).toBeUndefined();
    expect(deliveryAnswer(`[IMPORTANT: 2 background processes completed. Treat these results as one batch.]\n\n${ANSWERED}`)).toBeUndefined();
  });
});

describe("A message_agent call", () => {
  const args = { target: "beta", message: "PING-C-1794974808162 what is 2+2?" };

  it("is a message to the teammate it names", () => {
    expect(agentSend({ name: "message_agent", status: "done", args })).toEqual({ to: "@beta", text: args.message });
    expect(agentSend({ name: "message_agent", status: "done", args: { target: "beta, @gamma", message: "Status?" } })?.to).toBe("@beta, @gamma");
  });

  it("carries Hermes's answer once the call has one", () => {
    expect(agentSend({ name: "message_agent", status: "done", args, result: ACK })).toEqual({ to: "@beta", text: args.message, ack: { kind: "queued", deliveryId: ID, to: "@beta" } });
    const refused = JSON.stringify({ error: "This install is not Bot-Mode-managed.", reason: "not_managed" });
    expect(agentSend({ name: "message_agent", status: "done", args, result: refused })?.ack).toEqual({ kind: "refused", why: "This install is not Bot-Mode-managed." });
    expect(agentSend({ name: "message_agent", status: "done", args, result: "not json" })).toEqual({ to: "@beta", text: args.message });
  });

  it("stays a tool call when it withdraws a request, names nobody, says nothing or was stopped", () => {
    expect(agentSend({ name: "message_agent", status: "done", args: { target: "beta", cancel: ID } })).toBeUndefined();
    expect(agentSend({ name: "message_agent", status: "done", args: { message: "Hello" } })).toBeUndefined();
    expect(agentSend({ name: "message_agent", status: "done", args: { target: "beta" } })).toBeUndefined();
    expect(agentSend({ name: "message_agent", status: "done" })).toBeUndefined();
    expect(agentSend({ name: "message_agent", status: "stopped", args: { target: "beta", message: "Hello" } })).toBeUndefined();
  });

  it("is nothing for any other tool, whatever its arguments", () => {
    expect(agentSend({ name: "terminal", status: "done", args })).toBeUndefined();
  });
});
